"""CodeBrain's memory 🧠

It remembers 4 kinds of things (all saved in brain/memory.json):
  - profile  : stuff about YOU (name, what you like, your skill level)
  - fixes    : every bug it fixed, so it doesn't make the same mistake again
  - projects : your games/programs + plans for future ones
  - notes    : anything you tell it to "remember"
"""

import json
import re
import time
import uuid
from pathlib import Path

from codebrain.paths import brain_dir, projects_dir

CATEGORIES = ("profile", "fixes", "projects", "notes")

ZOMBIE_PLAN = """\
GAME PLAN: "Graveyard Zombies" - a 3D first-person zombie shooter (Python + Ursina).
The user is building this THEMSELF. Teach it step by step; don't dump the whole game at once.
- Map: graveyard at night - fog, tombstones, big glowing moon, random lightning flashes,
  zombies rise out of graves.
- Player: WASD + mouse look, Sprint (Shift), Jump (Space), Crouch (Ctrl), Flashlight (F).
- Weapons: laser gun (never runs out; color changes with upgrades: green -> blue -> purple -> gold)
  and a sword for close range.
- Enemies: blocky zombies with red glowing eyes, come in waves. Some are fast runners.
  BOSS zombie every 5 waves: ground slam shockwave (jump over it), summons minions,
  throws tombstones - gets harder as its health drops.
- Zombies sometimes drop health pickups. Coins for killing zombies.
- Upgrade shop between waves: laser damage+, max health+, sword range+, speed boots.
- HUD: health bar, wave number, minimap (red dots = zombies), kill counter, coins,
  damage numbers popping out of zombies.
- Menus: main menu (Play/Settings/Quit), pause (Esc), mouse sensitivity slider,
  difficulty Easy/Normal/Nightmare.
- Sounds generated by code (no downloaded files).
- Endless mode: survive as long as you can, save the high score.
Suggested build order: 1) ground+sky+player  2) tombstones+fog+moon  3) laser shooting
4) one zombie that chases you  5) health + game over  6) waves + spawning from graves
7) sword  8) HUD + minimap  9) coins + shop  10) boss  11) menus + difficulty
12) sounds + lightning + flashlight  13) high score saving."""

_WORD = re.compile(r"[a-zA-Z_][a-zA-Z0-9_]+")
_STOP = set("the a an and or to of in on is it this that for with my me i you be are was "
            "can do how what why make code python".split())


def _words(text):
    return {w.lower() for w in _WORD.findall(text or "") if w.lower() not in _STOP and len(w) > 2}


def _new_id():
    return uuid.uuid4().hex[:8]


class Memory:
    def __init__(self, path=None):
        self.path = Path(path) if path else brain_dir() / "memory.json"
        self.data = {c: [] for c in CATEGORIES}
        if self.path.exists():
            try:
                loaded = json.loads(self.path.read_text(encoding="utf-8"))
                for c in CATEGORIES:
                    self.data[c] = list(loaded.get(c, []))
            except (OSError, ValueError):
                # Keep a copy of the broken file instead of losing memories.
                self.path.rename(self.path.with_suffix(f".broken-{int(time.time())}.json"))
        if not self.data["projects"]:
            self.add_project("Graveyard Zombies", "3D first-person zombie shooter you're building yourself",
                             ZOMBIE_PLAN, save=False)
            self.save()

    def save(self):
        tmp = self.path.with_suffix(".tmp")
        tmp.write_text(json.dumps(self.data, indent=2, ensure_ascii=False), encoding="utf-8")
        tmp.replace(self.path)

    # ---------- adding ----------
    def _add(self, category, item, save=True):
        item.setdefault("id", _new_id())
        item.setdefault("created", time.strftime("%Y-%m-%d %H:%M"))
        self.data[category].append(item)
        if save:
            self.save()
        return item

    def remember_fact(self, text):
        text = text.strip().rstrip(".")
        if not text:
            return None
        for item in self.data["profile"]:
            if item["text"].lower() == text.lower():
                return item
        return self._add("profile", {"text": text})

    def add_note(self, text):
        return self._add("notes", {"text": text.strip()})

    def add_project(self, name, description, plan="", save=True):
        return self._add("projects", {"name": name, "description": description, "plan": plan}, save)

    def add_fix(self, error, lesson, confirmed=False):
        """Save a bug + how it got fixed. Same error again? Bump its counter instead."""
        key = error.strip().splitlines()[-1][:200] if error.strip() else error[:200]
        for item in self.data["fixes"]:
            if item["error"] == key:
                item["times_seen"] = item.get("times_seen", 1) + 1
                item["lesson"] = lesson or item["lesson"]
                item["confirmed"] = item.get("confirmed", False) or confirmed
                self.save()
                return item
        return self._add("fixes", {"error": key, "lesson": lesson.strip()[:600],
                                   "confirmed": confirmed, "times_seen": 1})

    def confirm_fix(self, fix_id):
        for item in self.data["fixes"]:
            if item["id"] == fix_id:
                item["confirmed"] = True
                self.save()
                return True
        return False

    def forget(self, item_id):
        for c in CATEGORIES:
            for item in self.data[c]:
                if item["id"] == item_id:
                    self.data[c].remove(item)
                    self.save()
                    return True
        return False

    # ---------- learning from chat ----------
    _FACT_PATTERNS = [
        (re.compile(r"\bmy name is ([a-z][\w' -]{0,30})", re.I), "User's name is {}"),
        (re.compile(r"\bcall me ([a-z][\w' -]{0,30})", re.I), "User wants to be called {}"),
        (re.compile(r"\bi (?:really )?(?:like|love|enjoy) ([^.!?\n]{3,80})", re.I), "User likes {}"),
        (re.compile(r"\bi (?:hate|don't like|dont like) ([^.!?\n]{3,80})", re.I), "User doesn't like {}"),
        (re.compile(r"\bmy favou?rite ([^.!?\n]{3,80})", re.I), "User's favorite {}"),
        (re.compile(r"\bi(?:'m| am) (\d{1,2}) (?:years|yrs)", re.I), "User is {} years old"),
    ]
    _REMEMBER = re.compile(r"^\s*(?:please\s+)?remember(?: that)?[:,]?\s+(.+)", re.I | re.S)

    def learn_from_message(self, message):
        """Pick up facts from what the user types. Returns list of new memories."""
        learned = []
        m = self._REMEMBER.match(message)
        if m:
            learned.append(self.add_note(m.group(1).strip()[:300]))
            return learned
        for pattern, template in self._FACT_PATTERNS:
            for found in pattern.findall(message):
                fact = template.format(found.strip())
                before = len(self.data["profile"])
                item = self.remember_fact(fact)
                if item and len(self.data["profile"]) > before:
                    learned.append(item)
        return learned

    # ---------- recalling ----------
    def relevant_fixes(self, query, limit=5):
        q = _words(query)
        scored = []
        for item in self.data["fixes"]:
            score = len(q & _words(item["error"] + " " + item["lesson"]))
            score += 0.5 if item.get("confirmed") else 0
            score += min(item.get("times_seen", 1), 5) * 0.2
            if score >= 1:
                scored.append((score, item))
        scored.sort(key=lambda s: -s[0])
        return [item for _, item in scored[:limit]]

    def scan_project_files(self, limit=30):
        """List the .py files in your projects folder (newest first)."""
        root = projects_dir()
        files = sorted(root.rglob("*.py"), key=lambda p: p.stat().st_mtime, reverse=True)[:limit]
        result = []
        for f in files:
            summary = ""
            try:
                for line in f.read_text(encoding="utf-8", errors="replace").splitlines()[:15]:
                    s = line.strip().strip('#"\' ')
                    if s:
                        summary = s[:80]
                        break
            except OSError:
                pass
            result.append((str(f.relative_to(root)), summary))
        return result

    def context_text(self, query="", include_plans=True):
        """Everything worth telling the brain, as text for its system prompt."""
        lines = []
        if self.data["profile"]:
            lines.append("WHAT YOU REMEMBER ABOUT THE USER:")
            lines += [f"- {i['text']}" for i in self.data["profile"][-30:]]
        if self.data["notes"]:
            lines.append("THINGS THE USER ASKED YOU TO REMEMBER:")
            lines += [f"- {i['text']}" for i in self.data["notes"][-30:]]
        fixes = self.relevant_fixes(query)
        if fixes:
            lines.append("PAST BUGS + LESSONS (don't repeat these mistakes):")
            lines += [f"- Error: {i['error']} -> Lesson: {i['lesson']}" for i in fixes]
        if self.data["projects"]:
            lines.append("THE USER'S PROJECTS:")
            q = _words(query)
            for p in self.data["projects"]:
                lines.append(f"- {p['name']}: {p['description']}")
                if include_plans and p.get("plan") and (q & _words(p["name"] + " " + p["plan"])):
                    lines.append(p["plan"])
        files = self.scan_project_files(limit=15)
        if files:
            lines.append("FILES IN THE USER'S PROJECTS FOLDER:")
            lines += [f"- {name}" + (f"  ({summary})" if summary else "") for name, summary in files]
        return "\n".join(lines)
